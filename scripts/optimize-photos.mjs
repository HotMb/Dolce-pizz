// Pizza photo pipeline: `npm run photos`.
// Drop a top-view photo named after the recipe id (e.g. `diavulo.png`) in assets-src/pizzas/, then run this.
// Each photo is centred on the pizza, cut out on a transparent background (so slices and cards float on
// any surface) and exported as WebP at 320/640/1024 px. lib/pizza-photos.ts lists the recipes that have one,
// so a recipe without photo shows a placeholder instead of a broken image.
import {readdirSync,mkdirSync,writeFileSync,rmSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import sharp from 'sharp';

const root=fileURLToPath(new URL('../',import.meta.url));
const source=path.join(root,'assets-src/pizzas'),target=path.join(root,'public/assets/pizzas');
const WIDTHS=[320,640,1024],SIDE=1024;
mkdirSync(target,{recursive:true});

// Feathered disc: fully opaque inside the crust, fading over the last 3% so the edge stays soft.
const disc=Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${SIDE}" height="${SIDE}"><defs><radialGradient id="g"><stop offset=".955" stop-color="#fff"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient></defs><circle cx="${SIDE/2}" cy="${SIDE/2}" r="${SIDE/2}" fill="url(#g)"/></svg>`);

async function bounds(file){
 // Pizza pixels are much brighter than the near-black studio background.
 const {data,info}=await sharp(file).greyscale().raw().toBuffer({resolveWithObject:true});
 let x0=info.width,y0=info.height,x1=0,y1=0;
 for(let y=0;y<info.height;y+=2)for(let x=0;x<info.width;x+=2)if(data[y*info.width+x]>48){if(x<x0)x0=x;if(x>x1)x1=x;if(y<y0)y0=y;if(y>y1)y1=y;}
 if(x1<=x0||y1<=y0)throw new Error(`${path.basename(file)} : aucune pizza détectée sur un fond sombre.`);
 return {cx:(x0+x1)/2,cy:(y0+y1)/2,r:((x1-x0)+(y1-y0))/4,width:info.width,height:info.height};
}

const ids=[];
for(const name of readdirSync(source).filter(f=>/\.(png|jpe?g|webp)$/i.test(f)).sort()){
 const id=name.replace(/\.[^.]+$/,'').toLowerCase(),file=path.join(source,name);
 const b=await bounds(file),half=Math.round(b.r*1.02);
 // Square crop centred on the pizza; pad with black when the pizza touches the photo edge.
 const left=Math.round(b.cx-half),top=Math.round(b.cy-half),size=half*2;
 const pad={top:Math.max(0,-top),left:Math.max(0,-left),bottom:Math.max(0,top+size-b.height),right:Math.max(0,left+size-b.width)};
 const square=await sharp(file).extend({...pad,background:'#000'}).extract({left:left+pad.left,top:top+pad.top,width:size,height:size}).resize(SIDE,SIDE).ensureAlpha().composite([{input:disc,blend:'dest-in'}]).png().toBuffer();
 for(const w of WIDTHS)await sharp(square).resize(w,w).webp({quality:w>640?84:80,alphaQuality:90,effort:5}).toFile(path.join(target,`${id}-${w}.webp`));
 ids.push(id);console.log(`✓ ${id}`);
}
// Remove exports whose source photo was deleted.
for(const f of readdirSync(target)){const id=f.replace(/-(\d+)\.webp$/,'');if(!ids.includes(id)||!/-\d+\.webp$/.test(f))rmSync(path.join(target,f));}
writeFileSync(path.join(root,'lib/pizza-photos.ts'),`// Generated by scripts/optimize-photos.mjs — do not edit by hand.\nexport const photoWidths=${JSON.stringify(WIDTHS)} as const;\nexport const pizzaPhotos:ReadonlySet<string>=new Set(${JSON.stringify(ids)});\n`);
console.log(`${ids.length} photo(s) prête(s) dans public/assets/pizzas/.`);
